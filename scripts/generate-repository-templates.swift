#!/usr/bin/env swift
// Generates Packages/EspalierKit/Sources/EspalierCore/App/RepositoryTemplateData.swift:
// the .gitignore templates and licenses Create a New Repository offers
// (desktop's ui/add-repository/gitignores.ts and licenses.ts read the same
// data from its bundle).
//
// The input is a built desktop's `static` folder, which holds
// - `gitignore/*.gitignore`: github/gitignore's top-level templates
//   (CC0-1.0), the only ones desktop lists;
// - `available-licenses.json`: choosealicense.com's licenses that aren't
//   hidden, as desktop's script/build.ts bundles them (`name`, `featured`,
//   `hidden`, `body` with its `[year]`/`{fullname}` tokens).
//
// Usage:
//   swift scripts/generate-repository-templates.swift \
//     "/Applications/GitHub Desktop.app/Contents/Resources/app/static" \
//     Packages/EspalierKit/Sources/EspalierCore/App/RepositoryTemplateData.swift

import Foundation

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
    FileHandle.standardError.write(Data("usage: generate-repository-templates.swift <desktop static folder> <output.swift>\n".utf8))
    exit(64)
}
let staticFolder = URL(filePath: arguments[1], directoryHint: .isDirectory)
let output = URL(filePath: arguments[2])

/// `text` as a Swift string literal: printable ASCII as is, everything else
/// escaped, so the file holds no invisible or non-ASCII characters.
func literal(_ text: String) -> String {
    var result = "\""
    for scalar in text.unicodeScalars {
        switch scalar {
        case "\\": result += "\\\\"
        case "\"": result += "\\\""
        case "\n": result += "\\n"
        case "\r": result += "\\r"
        case "\t": result += "\\t"
        case " "..."~": result.unicodeScalars.append(scalar)
        default: result += "\\u{\(String(scalar.value, radix: 16, uppercase: true))}"
        }
    }
    return result + "\""
}

// The .gitignore templates, by name (the file name without `.gitignore`).
let gitIgnoreFolder = staticFolder.appending(path: "gitignore", directoryHint: .isDirectory)
let gitIgnoreFiles = try FileManager.default.contentsOfDirectory(atPath: gitIgnoreFolder.path(percentEncoded: false))
    .filter { $0.hasSuffix(".gitignore") }
var gitIgnores: [(name: String, text: String)] = []
for file in gitIgnoreFiles {
    let data = try Data(contentsOf: gitIgnoreFolder.appending(path: file))
    guard let text = String(data: data, encoding: .utf8) else {
        FileHandle.standardError.write(Data("\(file) isn't UTF-8\n".utf8))
        exit(65)
    }
    gitIgnores.append((String(file.dropLast(".gitignore".count)), text))
}
// By name, as the menu lists them.
gitIgnores.sort { $0.name.compare($1.name, options: [.caseInsensitive, .numeric]) == .orderedAscending }

// The licenses, as desktop bundles them.
struct License: Decodable {
    let name: String
    let featured: Bool
    let hidden: Bool
    let body: String
}
let licenseData = try Data(contentsOf: staticFolder.appending(path: "available-licenses.json"))
let licenses = try JSONDecoder().decode([License].self, from: licenseData)
    .filter { !$0.hidden }
    .sorted { $0.name.compare($1.name, options: [.caseInsensitive]) == .orderedAscending }

var source = """
// Generated by scripts/generate-repository-templates.swift; don't edit.
// The .gitignore templates are github/gitignore's top-level ones (CC0-1.0),
// and the licenses choosealicense.com's that aren't hidden (its data is MIT
// licensed: "Copyright (c) 2013-2023 GitHub, Inc. and contributors"), as
// GitHub Desktop 3.6.6 bundles them.

extension RepositoryTemplates {
    /// The .gitignore templates, by name, sorted.
    nonisolated static let bundledGitIgnores: [(name: String, text: String)] = [

"""
for template in gitIgnores {
    source += "        (\(literal(template.name)), \(literal(template.text))),\n"
}
source += """
    ]

    /// The licenses, sorted by name.
    nonisolated static let bundledLicenses: [RepositoryLicense] = [

"""
for license in licenses {
    source += "        RepositoryLicense(name: \(literal(license.name)), isFeatured: \(license.featured), body: \(literal(license.body))),\n"
}
source += """
    ]
}

"""
try Data(source.utf8).write(to: output)
print("Wrote \(gitIgnores.count) .gitignore templates and \(licenses.count) licenses to \(output.path(percentEncoded: false))")
