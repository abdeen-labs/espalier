#!/usr/bin/env swift
// Generates Packages/EspalierKit/Sources/EspalierCore/Text/EmojiData.swift:
// the emoji shortcodes commit messages render (desktop's lib/read-emoji.ts
// reads the same table from its bundle at launch).
//
// The input is a built desktop's `emoji.json`: gemoji's `db/emoji.json`
// (MIT), at the commit desktop's `gemoji` submodule pins, which desktop's
// script/build.ts copies next to its entry point. Each entry has `aliases`
// and, unless it's one of GitHub's custom emoji (`:shipit:`, `:octocat:`),
// the `emoji` characters. Custom emoji are images desktop bundles; Espalier
// bundles no images, so their shortcodes stay text, but they're listed so
// the tokenizer matches what desktop's does.
//
// Usage:
//   swift scripts/generate-emoji.swift \
//     "/Applications/GitHub Desktop.app/Contents/Resources/app/emoji.json" \
//     Packages/EspalierKit/Sources/EspalierCore/Text/EmojiData.swift

import Foundation

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
    FileHandle.standardError.write(Data("usage: generate-emoji.swift <desktop emoji.json> <output.swift>\n".utf8))
    exit(64)
}
let input = URL(filePath: arguments[1])
let output = URL(filePath: arguments[2])

/// `text` as a Swift string literal: printable ASCII as is, everything else
/// escaped, so the file holds no invisible or non-ASCII characters.
func literal(_ text: String) -> String {
    var result = "\""
    for scalar in text.unicodeScalars {
        switch scalar {
        case "\\": result += "\\\\"
        case "\"": result += "\\\""
        case " "..."~": result.unicodeScalars.append(scalar)
        default: result += "\\u{\(String(scalar.value, radix: 16, uppercase: true))}"
        }
    }
    return result + "\""
}

struct Definition: Decodable {
    let emoji: String?
    let aliases: [String]
}

let definitions = try JSONDecoder().decode([Definition].self, from: Data(contentsOf: input))

var source = """
// Generated by scripts/generate-emoji.swift; don't edit.
// gemoji's db/emoji.json (MIT: github/gemoji at 50865e8, the commit
// desktop's `gemoji` submodule pins), as GitHub Desktop 3.6.6 bundles it:
// each emoji's characters (nil for GitHub's custom emoji, which are images)
// and its aliases, in the file's order.

extension EmojiTable {
    /// gemoji's emoji, in its order.
    nonisolated static let bundled: [(emoji: String?, aliases: [String])] = [

"""
for definition in definitions {
    let emoji = definition.emoji.map(literal) ?? "nil"
    let aliases = definition.aliases.map(literal).joined(separator: ", ")
    source += "        (\(emoji), [\(aliases)]),\n"
}
source += """
    ]
}

"""
try Data(source.utf8).write(to: output)
print("Wrote \(definitions.count) emoji to \(output.path(percentEncoded: false))")
